    <p>Google et Calendly peuvent traiter des données aux États-Unis. D’après les informations qu’ils publient, ce transfert s’appuie sur le cadre de protection des données UE–États-Unis ou sur des clauses contractuelles types. L’OpenStreetMap Foundation est établie au Royaume-Uni, qui bénéficie d’une décision d’adéquation de la Commission européenne.</p>
    <p>Les messages et les dossiers de candidature sont destinés à l’école, à Paris. Ils ne sont pas envoyés à ces prestataires, sauf si vous saisissez vous-même un rendez-vous dans Calendly.</p>

    <h2>7. Combien de temps les données sont gardées</h2>
    <ul>
        <li>Message de contact et dossier de candidature : pendant la durée indiquée sur le formulaire au moment de l’envoi. Cette durée est d’un an par défaut. L’école peut la régler entre 30 jours et sept ans. Passé ce délai, le message ou le dossier et ses pièces sont supprimés automatiquement.</li>
        <li>E-mails échangés ensuite avec l’équipe : le temps de traiter la demande, puis selon la durée nécessaire au suivi.</li>
        <li>Compteur anti-abus : une heure.</li>
        <li>Choix de cookies : six mois sur votre terminal.</li>
        <li>Journaux de connexion de l’hébergeur : selon la durée qu’il applique pour la sécurité du serveur.</li>
    </ul>
    <p>Si une candidature aboutit à une inscription, les pièces utiles au dossier d’élève sortent de ce délai de site et suivent les règles applicables au dossier de formation.</p>

    <h2>8. Sécurité</h2>
    <p>Le site est servi en HTTPS. Les messages et les candidatures ne sont pas des pages publiques. L’accès aux dossiers dans l’administration est réservé aux personnes habilitées. L’adresse IP d’un message est conservée sous forme d’empreinte, et non en clair. Les pièces déposées portent un nom aléatoire.</p>
    <p>Aucune mesure n’écarte tout risque. En cas d’accès non autorisé présentant un risque pour les personnes, l’école en informe les personnes concernées et la CNIL lorsque la réglementation l’exige.</p>

