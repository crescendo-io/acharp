    <p>Le choix et sa date sont conservés dans le cookie <strong>acharp_consent</strong>, sur le terminal, pendant six mois. Passé ce délai, la question est reposée. Ce délai suit la recommandation de la CNIL du 17 septembre 2020 relative aux cookies et autres traceurs.</p>
    <p>La page de politique reste lisible sans avoir à accepter de cookie. Le lien « Gestion des cookies », en bas de chaque page, rouvre le choix.</p>

