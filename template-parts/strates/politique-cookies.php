    <h2>2. Ce qu’est un cookie</h2>
    <p>Un cookie est un petit fichier enregistré sur le terminal (ordinateur, téléphone, tablette) lors d’une visite. Des traceurs proches (stockage du navigateur, pixels, identifiants publicitaires) suivent le même régime. Le dépôt d’un cookie non indispensable est soumis à un consentement préalable, libre, spécifique, éclairé et univoque.</p>
    <p>Poursuivre la navigation, fermer la fenêtre ou faire défiler la page ne vaut pas accord. Tant qu’aucun bouton n’a été activé, seuls les cookies nécessaires existent, et aucun traceur d’audience ou contenu externe n’est chargé.</p>

    <h2>3. Comment le choix est recueilli</h2>
